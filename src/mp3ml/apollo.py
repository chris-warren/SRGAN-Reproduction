"""Reading the Apollo preprocessed dataset, for an Apollo-vs-SRGAN comparison.

Apollo (Li et al., <https://github.com/JusperLee/Apollo>) is the other model
this project replicates, and comparing the two requires feeding both the *same*
audio. `apollo_v1` is generated by the `data_prep` pipeline documented in the
README beside the data; this module reads it. The layout:

    hdf5_train/<stem>/<dataset>__<track>__<file>.hdf5
        "data": (n_windows, 2, 264600) float32   -- CLEAN ONLY
    eval/val.hdf5, test/test.hdf5
        "ori", "codec": (N, 2, 264600) float32, plus "clip_id"

Three properties of that layout drive everything here:

**The training set has no degraded side.** Apollo applies MP3 inside its
`__getitem__`, so the stored windows are the originals. Our own pipeline
(`mp3ml.waveform`) stores pre-aligned pairs instead, so Apollo data cannot be
dropped into `WaveformPairs` -- the degraded half does not exist on disk.

**It is stereo at 44.1 kHz, 6 s per window.** The reproduction's generator is
single-channel: in a `(2, bins, frames)` spectrogram the 2 is real/imag, not
audio channels (`mp3ml.stft`). Channels are therefore indexed *separately*, the
standard way to apply a single-channel model to stereo -- it keeps Table 1
untouched and doubles the number of training items.

**Apollo's bitrates are 24/32/48/64/96/128 kbit/s**, where the paper uses
16/32/64. Only **32 and 64** are in both, so those are the rates at which a
result is comparable to Apollo *and* to the paper's Table 2. 16 kbit/s -- the
paper's headline case -- is not available in this dataset at all.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass
from pathlib import Path

import numpy as np

logger = logging.getLogger(__name__)

#: Samples per stored window: 6 s at 44.1 kHz.
WINDOW_SAMPLES = 264_600

#: Bitrates the Apollo pipeline generates (kbit/s), from its README.
APOLLO_BITRATES = (24, 32, 48, 64, 96, 128)

#: MP3 output sample rate per bitrate for **mono** LAME input at 44.1 kHz,
#: MEASURED 2026-10-21 with `ffprobe` (not assumed). Below 64 kbit/s mono LAME
#: silently resamples, which changes the degradation into something the paper
#: never measured and doubles the priming delay:
#:
#:     24 kbit/s -> 16000 Hz      48 kbit/s -> 32000 Hz
#:     32 kbit/s -> 22050 Hz      64, 96, 128 -> 44100 Hz
#:
#: This is the 64 kbit/s mono CBR floor that CLAUDE.md warns about. Apollo
#: encodes *stereo*, where the floor is 112 kbit/s, so most of its own rates
#: resample too -- but that is Apollo's baseline, not something to import.
MONO_OUTPUT_SAMPLERATE = {24: 16_000, 32: 22_050, 48: 32_000, 64: 44_100, 96: 44_100, 128: 44_100}

#: Apollo rates that survive mono encoding without resampling.
MONO_SAFE_BITRATES = (64, 96, 128)

#: **64 kbit/s is the only usable rate for an Apollo-vs-paper comparison.** It
#: is the sole member of Apollo's {24, 32, 48, 64, 96, 128} that is also in the
#: paper's {16, 32, 64} *and* resample-free in mono. 32 kbit/s is in both sets
#: but resamples to 22.05 kHz; 96 and 128 are clean but absent from the paper.
#: A result at 64 kbit/s is comparable in both directions at once.
COMPARABLE_BITRATES = (64,)

#: MP3's inherent priming delay in samples at 44.1 kHz: 576 encoder + 529
#: decoder. It holds only when the encoder does not resample; at 32 kbit/s mono
#: the measured delay is 2210, and `verify_constant_delay` caught exactly that
#: before any data was built. This project has lost days to alignment that was
#: assumed rather than measured (REPRODUCTION.md §5), so the constant is
#: checked, never trusted.
MP3_PRIMING_DELAY = 1105


@dataclass(frozen=True)
class Window:
    """One addressable training item: a channel of one window of one file."""

    path: Path
    window: int
    channel: int
    stem: str


def stem_dirs(root: Path) -> list[Path]:
    """Stem directories under `hdf5_train`, sorted for reproducibility."""
    train = root / "hdf5_train"
    if not train.is_dir():
        raise FileNotFoundError(f"{train} not found — is this an apollo_v1 root?")
    return sorted(d for d in train.iterdir() if d.is_dir())


def index_windows(root: Path, stems: tuple[str, ...] | None = None) -> list[Window]:
    """Every (file, window, channel) triple in the training set.

    Reads only each file's dataset *shape*, not its contents, so indexing 1,700
    files is cheap. Files with no windows are skipped: the generator records
    them in `manifest.csv` with `n_windows = 0` rather than writing an empty
    `data`, but a defensive skip costs nothing.
    """
    import h5py

    out: list[Window] = []
    for d in stem_dirs(root):
        if stems is not None and d.name not in stems:
            continue
        for path in sorted(d.glob("*.hdf5")):
            with h5py.File(path, "r") as f:
                if "data" not in f:
                    logger.warning("%s has no 'data' dataset — skipping", path.name)
                    continue
                n_windows, n_ch, n_samples = f["data"].shape
            if n_samples != WINDOW_SAMPLES:
                raise ValueError(
                    f"{path} has {n_samples} samples per window, expected "
                    f"{WINDOW_SAMPLES} — a different apollo_v1 revision?"
                )
            out.extend(Window(path, w, c, d.name) for w in range(n_windows) for c in range(n_ch))
    if not out:
        raise ValueError(f"no windows found under {root / 'hdf5_train'}")
    return out


def read_window(path: Path, window: int, channel: int) -> np.ndarray:
    """One channel of one stored window as float32 in [-1, 1]."""
    import h5py

    with h5py.File(path, "r") as f:
        return np.asarray(f["data"][window, channel], dtype=np.float32)


def read_eval_pairs(root: Path, split: str) -> tuple[np.ndarray, np.ndarray, list[str]]:
    """The packed (original, codec) evaluation pairs and their clip ids.

    Unlike the training set these *are* pairs, degraded by Apollo's own
    `codec_simu` at a fixed bitrate per clip, so scoring on them is directly
    comparable to Apollo's published numbers.

    **Caveat, from the dataset's own README:** `codec_simu` leaves roughly
    7-15% of clips out of step with their target, mostly by the full
    `MP3_PRIMING_DELAY`. The manifest records `residual_lag_samples` and
    `aligned` per clip; filter on those before treating a metric as a
    restoration result rather than an alignment artefact.
    """
    import h5py

    name = {"val": "eval/val.hdf5", "test": "test/test.hdf5"}
    if split not in name:
        raise ValueError(f"split must be 'val' or 'test', got {split!r}")
    path = root / name[split]
    with h5py.File(path, "r") as f:
        ori = np.asarray(f["ori"], dtype=np.float32)
        codec = np.asarray(f["codec"], dtype=np.float32)
        ids = [c.decode() if isinstance(c, bytes) else str(c) for c in f["clip_id"][:]]
    return ori, codec, ids


def check_tools() -> None:
    """Fail now if `lame` or `ffmpeg` is missing, not at the first batch.

    `degrade` shells out per item, so without these the run dies on step 1 --
    after the model is built, the corpus is indexed and, on a cluster, an
    allocation is already running. Clusters expose them through modules
    (`module load ffmpeg`), so the failure is both likely and cheap to avoid.
    """
    import shutil

    missing = [t for t in ("lame", "ffmpeg") if shutil.which(t) is None]
    if missing:
        raise FileNotFoundError(
            f"{', '.join(missing)} not on PATH. MP3 degradation runs per training "
            "item, so training cannot start without them. On a cluster try "
            "`module load ffmpeg` (lame often ships with it); locally, install "
            "them from your package manager."
        )


def degrade(pcm: np.ndarray, bitrate_kbps: int, samplerate: int = 44100) -> np.ndarray:
    """MP3 encode and decode `pcm` in memory, returning float32 the same length.

    Piped rather than written to disk: a `Dataset` calls this once per item, and
    at 40,000 steps x batch 12 the temporary files would be millions of creates.

    The result is **delay-corrected and length-matched**, so the return value
    lines up sample-for-sample with the input. MP3 prepends
    `MP3_PRIMING_DELAY` samples of priming; `verify_constant_delay` checks that
    the constant is right for this encoder rather than assuming it.

    Encoder flags match `mp3ml.encode.reference_encode` (`-t`, CBR, mono) so
    the degradation is the same one the rest of the project measures.
    """
    import subprocess

    if bitrate_kbps not in MONO_SAFE_BITRATES:
        rate = MONO_OUTPUT_SAMPLERATE.get(bitrate_kbps)
        detail = f"resamples 44100 -> {rate} Hz" if rate else "is not a rate we have measured"
        raise ValueError(
            f"{bitrate_kbps} kbit/s mono {detail}, so the pair would not be the "
            f"degradation the paper measures and MP3_PRIMING_DELAY would be wrong. "
            f"Mono-safe rates: {MONO_SAFE_BITRATES}; for a comparison use "
            f"{COMPARABLE_BITRATES[0]} kbit/s."
        )
    if pcm.dtype != np.int16:
        pcm = np.clip(pcm * 32768.0, -32768, 32767).astype(np.int16)
    cmd = (
        f"lame --quiet -t -r -s {samplerate / 1000.0} --bitwidth 16 --signed "
        f"--little-endian -m m --cbr -b {bitrate_kbps} - - | "
        f"ffmpeg -v error -i pipe: -f s16le -acodec pcm_s16le -ac 1 -ar {samplerate} -"
    )
    done = subprocess.run(
        ["bash", "-c", cmd],
        input=pcm.astype("<i2").tobytes(),
        capture_output=True,
        check=True,
    )
    out = np.frombuffer(done.stdout, dtype="<i2").astype(np.float32) / 32768.0
    out = out[MP3_PRIMING_DELAY:]
    if len(out) < len(pcm):
        out = np.pad(out, (0, len(pcm) - len(out)))
    return out[: len(pcm)]


def verify_constant_delay(
    pcm: np.ndarray, bitrates: tuple[int, ...] = COMPARABLE_BITRATES
) -> dict[int, int]:
    """Measure the residual lag after `degrade`, which must be 0 at every rate.

    `degrade` trims a hard-coded `MP3_PRIMING_DELAY`. That is only safe while
    the encoder really does prepend exactly that much, and this project has
    already lost days to alignment that was assumed rather than measured
    (REPRODUCTION.md §5, and the dataset README's note that Apollo's own
    `match2` leaves 7-15% of clips out of step). So the constant is checked
    against `mp3ml.waveform.estimate_lag`, the same estimator the main dataset
    builder trusts.

    Returns `{bitrate: residual_lag}`. Any nonzero value means `degrade` is
    producing misaligned pairs and must not be used for training.
    """
    from .align import estimate_lag

    clean_i16 = np.clip(pcm * 32768.0, -32768, 32767).astype(np.int16)
    residuals = {}
    for rate in bitrates:
        degraded = degrade(pcm, rate)
        deg_i16 = np.clip(degraded * 32768.0, -32768, 32767).astype(np.int16)
        residuals[rate] = estimate_lag(clean_i16, deg_i16, max_lag=5000)
    return residuals


class ApolloPairs:
    """`WaveformPairs`-compatible Dataset over the Apollo training windows.

    Returns exactly what `mp3ml.data.WaveformPairs` returns -- `degraded`
    `(2, n_bins, segment_frames)`, `clean` `(2, n_bins, output_frames)`,
    `clean_full`, `bitrate` -- so the Trainer needs no knowledge of where the
    audio came from. Only the source differs.

    **Degradation happens here, not on disk.** Apollo stores originals only, and
    the local disk has no room for a second copy (154 GB per bitrate). Doing it
    per item also matches Apollo's own loader, which keeps the comparison
    honest. The cost is real: roughly 470 ms per item, so this needs **16+
    dataloader workers** to keep a large GPU fed. `scripts/bench_apollo.py`
    measures it.

    **The whole 6 s window is degraded, then cropped.** Cropping first would
    hand the encoder an arbitrary start point on every item, giving each
    training segment a start transient that no real MP3 of a song contains.

    **Apollo peak-normalises each pair; we do not.** Its loader divides both
    signals by the larger of their peaks. The paper specifies no normalisation,
    so this stays faithful to the paper and is a **[D]** against Apollo.
    """

    def __init__(
        self,
        cfg,
        split: str = "train",
        stems: tuple[str, ...] | None = None,
        seed: int = 0,
        random_crop: bool = True,
        bitrate: int | None = None,
    ) -> None:
        from .config import segment_samples, target_crop

        if split != "train":
            raise ValueError(
                f"split={split!r}: Apollo stores only a training set under "
                "hdf5_train; use `read_eval_pairs` for val/test, which are "
                "packed (ori, codec) pairs with their own alignment flags"
            )
        rates = (bitrate,) if bitrate is not None else tuple(cfg.data.bitrates)
        bad = [r for r in rates if r not in MONO_SAFE_BITRATES]
        if bad:
            raise ValueError(
                f"bitrate(s) {bad} resample in mono (see MONO_OUTPUT_SAMPLERATE); "
                f"use {COMPARABLE_BITRATES[0]} kbit/s for a comparison run"
            )
        self.cfg = cfg
        self.rates = rates
        self.seg_samples = segment_samples(cfg)
        self.crop = target_crop(cfg)
        self.seed = seed
        self.random_crop = random_crop
        check_tools()
        root = Path(cfg.data.root)
        if not root.is_dir():
            raise FileNotFoundError(
                f"corpus root {root} does not exist. Set $APOLLO_DATA or pass "
                "--data-root; the path in the YAML is the workstation's external "
                "drive and will not exist on a cluster."
            )
        self.windows = index_windows(
            root, stems if stems is not None else tuple(cfg.data.train_stems)
        )

    def __len__(self) -> int:
        return len(self.windows)

    def __getitem__(self, i: int) -> dict:
        import torch

        from .stft import stft

        w = self.windows[i]
        clean = read_window(w.path, w.window, w.channel)

        if self.random_crop:
            rate = self.rates[int(torch.randint(0, len(self.rates), (1,)).item())]
            span = len(clean) - self.seg_samples + 1
            offset = int(torch.randint(0, max(span, 1), (1,)).item()) if span > 1 else 0
        else:
            # Fixed per item, so two runs of one checkpoint score the same audio
            # (the mistake `WaveformPairs` documents for evaluation).
            gen = torch.Generator().manual_seed(self.seed * 1_000_003 + i)
            rate = self.rates[int(torch.randint(0, len(self.rates), (1,), generator=gen).item())]
            span = len(clean) - self.seg_samples + 1
            offset = int(torch.randint(0, span, (1,), generator=gen).item()) if span > 1 else 0

        degraded = degrade(clean, rate)
        sl = slice(offset, offset + self.seg_samples)
        s = self.cfg.stft
        to_spec = lambda a: stft(  # noqa: E731
            torch.from_numpy(np.ascontiguousarray(a[sl])).float(),
            n_fft=s.n_fft,
            hop=s.hop,
            n_bins=s.n_bins,
        )
        clean_full, degraded_spec = to_spec(clean), to_spec(degraded)
        lo, hi = self.crop
        return {
            "degraded": degraded_spec,
            "clean": clean_full[..., lo:hi],
            "clean_full": clean_full,
            "bitrate": torch.tensor(rate),
        }


def read_eval_manifest(root: Path, split: str) -> list[dict]:
    """Per-clip metadata for an evaluation split, as written by `make_eval_set`.

    Carries `bitrate_kbps`, `residual_lag_samples` and `aligned` per clip, which
    is what makes these pairs usable despite `codec_simu` leaving some of them
    out of step.
    """
    import csv

    name = {"val": "eval/val_manifest.csv", "test": "test/test_manifest.csv"}
    if split not in name:
        raise ValueError(f"split must be 'val' or 'test', got {split!r}")
    with (root / name[split]).open() as f:
        return list(csv.DictReader(f))


class ApolloEvalPairs:
    """Apollo's packed (original, codec) evaluation clips, one bitrate at a time.

    These are the clips Apollo itself is scored on, so metrics computed here are
    directly comparable to its published numbers. Unlike the training set they
    are already pairs, so nothing is encoded at read time.

    **The recorded residual lag is corrected, not filtered.** Apollo's
    `codec_simu` re-aligns with `match2` and leaves roughly 7-15% of clips out
    of step — at 64 kbit/s, 1 of 50 validation clips, off by exactly the full
    `MP3_PRIMING_DELAY` because `match2` returned 0. The generator pipeline
    measured and stored each clip's `residual_lag_samples`, so shifting by it
    recovers every clip correctly aligned instead of discarding 2% of an
    already small set. Pass `aligned_only=True` to drop them instead, which is
    what Apollo's own `test.py` reports as its `aligned:*` rows.

    Items match `mp3ml.data`'s contract, and crops are **fixed**: an evaluation
    that moves its window cannot compare two checkpoints.
    """

    def __init__(
        self,
        cfg,
        split: str = "val",
        bitrate: int | None = None,
        aligned_only: bool = False,
        max_clips: int | None = None,
    ) -> None:
        from .config import segment_samples, target_crop

        root = Path(cfg.data.root)
        rate = bitrate if bitrate is not None else cfg.data.bitrates[0]
        manifest = read_eval_manifest(root, split)
        self.rows = [
            (i, r)
            for i, r in enumerate(manifest)
            if int(r["bitrate_kbps"]) == rate and (not aligned_only or int(r["aligned"]) == 1)
        ]
        if not self.rows:
            raise ValueError(
                f"no {split} clips at {rate} kbit/s"
                + (" that are aligned" if aligned_only else "")
                + f"; manifest has {sorted({int(r['bitrate_kbps']) for r in manifest})}"
            )
        if max_clips is not None:
            self.rows = self.rows[:max_clips]
        self.cfg = cfg
        self.split = split
        self.rate = rate
        self.seg_samples = segment_samples(cfg)
        self.crop = target_crop(cfg)
        self._path = root / {"val": "eval/val.hdf5", "test": "test/test.hdf5"}[split]
        self._h5 = None
        # Two channels per clip, indexed separately: the generator is
        # single-channel (see this module's docstring).
        self.n_channels = 2

    def __len__(self) -> int:
        return len(self.rows) * self.n_channels

    def __getitem__(self, i: int) -> dict:
        import h5py
        import torch

        from .stft import stft

        row_i, channel = divmod(i, self.n_channels)
        index, row = self.rows[row_i]
        if self._h5 is None:  # opened lazily so each worker gets its own handle
            self._h5 = h5py.File(self._path, "r")
        ori = np.asarray(self._h5["ori"][index, channel], dtype=np.float32)
        codec = np.asarray(self._h5["codec"][index, channel], dtype=np.float32)

        lag = int(row["residual_lag_samples"])
        if lag:
            codec = np.roll(codec, -lag)
            codec[-lag:] = 0.0 if lag > 0 else codec[-lag:]

        # Centre crop: fixed, and away from both ends so neither the encoder's
        # start transient nor any roll wrap-around lands in the scored window.
        start = max((len(ori) - self.seg_samples) // 2, 0)
        sl = slice(start, start + self.seg_samples)
        s = self.cfg.stft
        to_spec = lambda a: stft(  # noqa: E731
            torch.from_numpy(np.ascontiguousarray(a[sl])).float(),
            n_fft=s.n_fft,
            hop=s.hop,
            n_bins=s.n_bins,
        )
        clean_full, degraded = to_spec(ori), to_spec(codec)
        lo, hi = self.crop
        return {
            "degraded": degraded,
            "clean": clean_full[..., lo:hi],
            "clean_full": clean_full,
            "bitrate": torch.tensor(self.rate),
        }
